import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'

const root = new URL('../../../', import.meta.url)
const spec = JSON.parse(
  await readFile(new URL('openapi/openapi.json', root), 'utf8'),
)
const names = [
  'LinkPreviewRequest',
  'SendMessageRequest',
  'SendMediaRequest',
  'GeneratePreviewRequest',
  'GeneratedPreviewDto',
  'PreviewGenerationStatus',
  'PreviewThumbnailStatus',
]
function strip(value) {
  if (Array.isArray(value)) return value.map(strip)
  if (value !== null && typeof value === 'object')
    return Object.fromEntries(
      Object.entries(value)
        .filter(
          ([key, entry]) => key !== 'description' || typeof entry !== 'string',
        )
        .map(([key, entry]) => [key, strip(entry)]),
    )
  return value
}
const schemas = Object.fromEntries(
  names.map((name) => [name, strip(spec.components.schemas[name])]),
)
const data = JSON.stringify(schemas)
// OpenAPI owns shape; the production validator also owns canonical-event
// projection/reservations that JSON Schema cannot express. Any change to that
// policy requires an explicit regeneration and the shared boundary fixtures.
const policy = await readFile(
  new URL('crates/axon-core/src/link_preview.rs', root),
  'utf8',
)
const fingerprint = createHash('sha256').update(policy).digest('hex')
const swift = `// Generated by clients/web/scripts/share-contract.mjs from OpenAPI.\n// Server preview policy SHA-256: ${fingerprint}\nimport Foundation\nenum WireSchemas {\n  static let schemas = try! JSONSerialization.jsonObject(with: Data(base64Encoded: "${Buffer.from(data).toString('base64')}")!) as! [String: [String: Any]]\n}\n`
const path = new URL(
  'clients/web/src-tauri/incoming-share/Sources/AxonIncomingShare/WireSchemas.swift',
  root,
)
if (process.argv.includes('--write')) await writeFile(path, swift)
else if ((await readFile(path, 'utf8')) !== swift)
  throw new Error(
    `Incoming-share wire schemas drifted; regenerate ${fileURLToPath(path)}`,
  )
