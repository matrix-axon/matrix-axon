/// A progress stream that becomes permanently pending after its first close.
///
/// Matrix SDK progress and completion are separate channels. The completion
/// future may still be running when progress closes, so returning `None` again
/// would leave an always-ready branch in `tokio::select!` and busy-spin until
/// completion, cancellation, or timeout.
pub(crate) struct ProgressUntilClosed<S> {
    inner: S,
    closed: bool,
}

impl<S> ProgressUntilClosed<S>
where
    S: Stream + Unpin,
{
    pub(crate) fn new(inner: S) -> Self {
        Self {
            inner,
            closed: false,
        }
    }

    pub(crate) async fn next(&mut self) -> Option<S::Item> {
        if self.closed {
            return std::future::pending().await;
        }
        let next = self.inner.next().await;
        if next.is_none() {
            self.closed = true;
        }
        next
    }
}

/// Which device presents the QR image.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MatrixOAuthAcquirePresentation {
    /// Axon generates QR data for the existing trusted device to scan.
    Display,
    /// An Axon client scans QR data generated by the existing trusted device.
    Scan,
}

impl MatrixOAuthAcquirePresentation {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Display => "display",
            Self::Scan => "scan",
        }
    }
}

/// Stable Axon stage names; SDK enum names never cross `/v1/`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MatrixOAuthAcquireStage {
    Starting,
    QrReady,
    CheckCodeToDisplay,
    CheckCodeRequired,
    WaitingForAuthorization,
    SyncingSecrets,
    Done,
    Failed,
    Cancelled,
}

impl MatrixOAuthAcquireStage {
    fn is_terminal(self) -> bool {
        matches!(self, Self::Done | Self::Failed | Self::Cancelled)
    }
}

