#!/usr/bin/env bash
#
# Fail if a markdown file contains Liquid syntax (`{{` or `{%`).
#
# The Pages site is built by Jekyll (api-docs.yml), and Jekyll runs Liquid over
# every markdown file in the repository -- inside code fences and code spans
# too, and not only the pages anyone links to. The github-pages gem pins
# Jekyll 3.10, which has no `render_with_liquid: false`, so there is no switch
# to turn that off. What Liquid makes of text it did not expect depends on the
# text: `{{60, 85}` stopped the build outright (#924), `{{}}` and
# `{{ startsWith(...) && ... }}` only logged a warning, and `{{name}}` or
# `v{{ version }}` is valid Liquid, so it silently rendered as nothing and the
# published page lost the words. A scan for the opening delimiter catches all
# three kinds, which an eyeball of the build log does not.
#
# Fix it by rephrasing. In prose, the HTML entity `&#123;&#123;` renders as
# `{{` on both GitHub and the site. Inside a code span an entity is shown
# literally, so describe the placeholder in words instead. `{% raw %}` works
# but shows up as visible text on github.com, so do not reach for it.
#
# CHANGELOG.md is generated by scripts/release-notes.sh, which writes the entity
# form itself, so a PR title containing braces never reaches this check.
#
# Usage: scripts/check-liquid.sh FILE...
# pre-commit passes the changed markdown files; CI runs it over the whole tree
# through the same hook.
set -euo pipefail

status=0
for file in "$@"; do
	# grep exits 1 for "no match", which is the passing case, and 2 for an error
	# such as a missing or unreadable file, which must not pass unscanned.
	rc=0
	hits=$(grep -n -E '\{\{|\{%' -- "$file") || rc=$?
	if [ "$rc" -gt 1 ]; then
		echo "check-liquid: cannot scan $file" >&2
		exit "$rc"
	fi
	if [ -n "$hits" ]; then
		status=1
		while IFS= read -r line; do
			printf '%s:%s\n' "$file" "$line" >&2
		done <<<"$hits"
	fi
done

if [ "$status" -ne 0 ]; then
	cat >&2 <<'MSG'

check-liquid: the lines above contain `{{` or `{%`, which Jekyll treats as Liquid
when it builds the Pages site, so the text is dropped or the build fails.
Rephrase them. In prose, write the entity `&#123;&#123;` for `{{`; inside a
code span, describe the placeholder in words. Reasons are in
scripts/check-liquid.sh.
MSG
fi
exit "$status"
